function mergeIntoAgentsMd(existing: string, generated: string): string {
  const startIdx = existing.indexOf(STRUCTURA_MARKER_START)
  const endIdx = existing.indexOf(STRUCTURA_MARKER_END)

  const block = [
    "",
    STRUCTURA_MARKER_START,
    generated,
    STRUCTURA_MARKER_END,
    "",
  ].join("\n")

  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const before = existing.slice(0, startIdx).replace(/\n*$/, "")
    const after = existing.slice(endIdx + STRUCTURA_MARKER_END.length)
    return before + block + after
  }

  return existing.replace(/\n*$/, "") + block
}

function generateWindsurfRules(ir: ArchitectureIR): string {
  const lines: string[] = []
  lines.push("# Windsurf AI Rules — Structura Architecture")
  lines.push("")
  lines.push(`Project: ${ir.meta.projectName}`)
  lines.push(`Architecture: ${ir.meta.projectStyle}`)
  lines.push("")
  lines.push("## Rules")
  for (const dep of ir.dependencies) {
    if (!dep.allowed) {
      lines.push(`- NEVER import from ${dep.sourceId} into ${dep.targetId}`)
    }
  }
  for (const domain of ir.domains) {
    for (const forbidden of domain.cannotAccess) {
      lines.push(`- NEVER import from ${forbidden} inside ${domain.name}`)
    }
  }
  lines.push("")
  lines.push("## Constrained Domains")
  for (const p of ir.aiPolicies) {
    if (p.autonomy === "constrained") {
      lines.push(`- ${p.domainId}: AI must NOT modify code in this domain`)
    }
  }
  return lines.join("\n")
}

function generateContinueRc(ir: ArchitectureIR): string {
  const rules = []
  for (const dep of ir.dependencies) {
    if (!dep.allowed) {
      rules.push({
        id: `no-import-${dep.sourceId}-${dep.targetId}`,
        description: `Do not import from ${dep.sourceId} into ${dep.targetId}`,
      })
    }
  }
  for (const domain of ir.domains) {
    for (const forbidden of domain.cannotAccess) {
      rules.push({
        id: `no-access-${domain.name}-${forbidden}`,
        description: `${domain.name} must not access ${forbidden}`,
      })
    }
  }

  const obj: Record<string, unknown> = {
    name: ir.meta.projectName,
    description: `Architecture: ${ir.meta.projectStyle}`,
    rules,
    tabAutocompleteModel: {
      title: ir.meta.projectName,
    },
  }

  return JSON.stringify(obj, null, 2)
}

function generateAiderConventions(ir: ArchitectureIR): string {
  const lines: string[] = []
  lines.push("# Project Conventions")
  lines.push("")
  lines.push(`Architecture style: ${ir.meta.projectStyle}`)
  lines.push("")
  lines.push("## Domain structure")
  for (const domain of ir.domains) {
    lines.push(`- ${domain.name}: ${domain.path}`)
  }
  lines.push("")
  lines.push("## Import restrictions")
  for (const dep of ir.dependencies) {
    if (!dep.allowed) {
      lines.push(`- Do not create imports from ${dep.sourceId} to ${dep.targetId}`)
    }
  }
  return lines.join("\n")
}

