import type { ArchitectureIR } from "@structura/ir"
import { ensureConfig } from "../utils/config.js"

const STRUCTURA_MARKER_START = "<!-- STRUCTURA:ARCHITECTURE -->"
const STRUCTURA_MARKER_END = "<!-- /STRUCTURA:ARCHITECTURE -->"

interface Generator {
  id: string
  label: string
  filePath: (root: string) => string
  generate: (ir: ArchitectureIR) => string
  merge?: (existing: string, generated: string) => string
}

function generateCursorrules(ir: ArchitectureIR): string {
  const lines: string[] = []
  lines.push("# Structura Architecture Rules")
  lines.push("")
  lines.push(`## ${ir.meta.projectName}`)
  lines.push(`- Architecture Style: ${ir.meta.projectStyle}`)
  lines.push("")

  lines.push("## Domains")
  for (const domain of ir.domains) {
    const canAccess = domain.canAccess.length > 0
      ? domain.canAccess.join(", ")
      : "(none)"
    const cannotAccess = domain.cannotAccess.length > 0
      ? domain.cannotAccess.join(", ")
      : "(none)"
    lines.push(`### ${domain.name}`)
    lines.push(`- Path: \`${domain.path}\``)
    lines.push(`- Can access: ${canAccess}`)
    lines.push(`- Cannot access: ${cannotAccess}`)
    if (domain.naming?.files) lines.push(`- File naming: \`${domain.naming.files}\``)
    if (domain.naming?.exports) lines.push(`- Export naming: \`${domain.naming.exports}\``)
    lines.push("")
  }

  lines.push("## Dependencies")
  for (const dep of ir.dependencies) {
    const status = dep.allowed ? "allowed" : "forbidden"
    const reason = dep.reason ? ` (${dep.reason})` : ""
    lines.push(`- ${dep.sourceId} -> ${dep.targetId}: ${status}${reason}`)
  }
  lines.push("")

  for (const autonomy of ["constrained", "guided"] as const) {
    const domains = ir.aiPolicies.filter((p) => p.autonomy === autonomy)
    if (domains.length > 0) {
      const label = autonomy === "constrained"
        ? "Constrained Domains (AI cannot modify)"
        : "Guided Domains (AI must follow architecture)"
      lines.push(`## ${label}`)
      for (const p of domains) {
        lines.push(`- ${p.domainId}`)
      }
      lines.push("")
    }
  }

  return lines.join("\n")
}

function generateClaudeMd(ir: ArchitectureIR): string {
  const lines: string[] = []
  lines.push(`# ${ir.meta.projectName} — Architecture`)
  lines.push("")
  lines.push(`> Architecture style: **${ir.meta.projectStyle}**`)
  lines.push("")
  lines.push("## Domains")
  lines.push("")
  lines.push("| Domain | Path | Can Access | Cannot Access |")
  lines.push("|--------|------|------------|---------------|")
  for (const domain of ir.domains) {
    const can = domain.canAccess.join(", ") || "-"
    const cannot = domain.cannotAccess.join(", ") || "-"
    lines.push(`| ${domain.name} | \`${domain.path}\` | ${can} | ${cannot} |`)
  }
  lines.push("")
  lines.push("## Dependency Rules")
  lines.push("")
  for (const dep of ir.dependencies) {
    const icon = dep.allowed ? "✅" : "❌"
    const reason = dep.reason ? ` — ${dep.reason}` : ""
    lines.push(`- ${icon} **${dep.sourceId}** → **${dep.targetId}** (${dep.allowed ? "allowed" : "forbidden"})${reason}`)
  }
  lines.push("")
  lines.push("## AI Governance")
  lines.push("")
  if (ir.aiPolicies.length > 0) {
    lines.push("| Domain | Autonomy |")
    lines.push("|--------|----------|")
    for (const p of ir.aiPolicies) {
      const labels = { constrained: "🔒 Constrained", guided: "🧭 Guided", supervised: "👁 Supervised" }
      lines.push(`| ${p.domainId} | ${labels[p.autonomy] ?? p.autonomy} |`)
    }
  } else {
    lines.push("No AI policies defined.")
  }
  lines.push("")
  lines.push("---")
  lines.push("*This file is auto-generated by `structura sync-ai`. Do not edit manually.*")
  return lines.join("\n")
}

function generateCopilotInstructions(ir: ArchitectureIR): string {
  const lines: string[] = []
  lines.push("# Architecture Context for GitHub Copilot")
  lines.push("")
  lines.push(`Project: ${ir.meta.projectName}`)
  lines.push(`Architecture: ${ir.meta.projectStyle}`)
  lines.push("")
  lines.push("## Domain Boundaries")
  for (const domain of ir.domains) {
    lines.push(`- **${domain.name}** (\`${domain.path}\`)`)
    if (domain.cannotAccess.length > 0) {
      lines.push(`  - Do NOT import from: ${domain.cannotAccess.join(", ")}`)
    }
    if (domain.canAccess.length > 0) {
      lines.push(`  - May import from: ${domain.canAccess.join(", ")}`)
    }
  }
  lines.push("")
  lines.push("## Restricted Dependencies")
  for (const dep of ir.dependencies) {
    if (!dep.allowed) {
      lines.push(`- Do NOT create imports from **${dep.sourceId}** to **${dep.targetId}**`)
    }
  }
  return lines.join("\n")
}

