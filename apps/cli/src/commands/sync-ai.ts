export const syncAiCommand = createCommand("sync-ai")
  .description("Generate AI context files for multiple AI coding tools")
  .option("--cursor", "Generate .cursorrules (Cursor IDE)")
  .option("--claude", "Generate CLAUDE.md (Claude Code)")
  .option("--copilot", "Generate .github/copilot-instructions.md (GitHub Copilot)")
  .option("--opencode", "Generate/update AGENTS.md (OpenCode)")
  .option("--windsurf", "Generate .windsurfrules (Windsurf)")
  .option("--continue", "Generate .continuerc (Continue.dev)")
  .option("--aider", "Generate CONVENTIONS.md (Aider)")
  .option("--all", "Generate all targets (default)")
  .option("--dry-run", "Show generated content without writing files")
  .option("--force", "Overwrite existing files")
  .option("--auto", "Auto-generate config if missing (non-interactive)")
  .action(async (options: {
    cursor?: boolean; claude?: boolean; copilot?: boolean;
    opencode?: boolean; windsurf?: boolean; continue?: boolean;
    aider?: boolean; all?: boolean;
    dryRun?: boolean; force?: boolean; auto?: boolean;
  }) => {
    p.intro(pc.bold("structura sync-ai"))
    const s = p.spinner()

    s.start("Finding configuration")
    const { config } = await ensureConfig({ auto: options.auto })
    s.stop("Config loaded")

    const ir = generateIR(config)

    const explicitFlags = [
      options.cursor, options.claude, options.copilot,
      options.opencode, options.windsurf, options.continue,
      options.aider,
    ]
    const hasExplicitTarget = explicitFlags.some(Boolean)
    const all = options.all ?? !hasExplicitTarget

    const selected = generators.filter((g) => {
      if (all) return true
      return options[g.id as keyof typeof options] === true
    })

    if (selected.length === 0) {
      p.outro(`${pc.yellow("⚠")} No targets selected. Use --all or a specific flag.`)
      return
    }

    const root = process.cwd()
    const results: { label: string; status: "written" | "skipped" | "dry-run" }[] = []

    if (options.dryRun) {
      s.stop("Dry-run mode")
      for (const gen of selected) {
        const content = gen.generate(ir)
        console.log(`\n${pc.bold(`=== ${gen.label} ===`)}`)
        console.log(content)
        results.push({ label: gen.label, status: "dry-run" })
      }
      const labels = results.map((r) => `  ${pc.dim("~")} ${r.label}`).join("\n")
      console.log(`\n${pc.bold("Would generate:")}\n${labels}`)
      p.outro(pc.yellow("⚠") + " Dry-run complete — no files written")
      return
    }

    for (const gen of selected) {
      const path = gen.filePath(root)
      const dir = path.includes("\\") ? path.substring(0, path.lastIndexOf("\\"))
        : path.includes("/") ? path.substring(0, path.lastIndexOf("/"))
        : ""

      const fileExists = existsSync(path)

      if (fileExists && !options.force) {
        if (gen.merge && gen.id === "opencode") {
          const existing = readFileSync(path, "utf-8")
          const generated = gen.generate(ir)
          const merged = gen.merge(existing, generated)
          writeFileSync(path, merged, "utf-8")
          results.push({ label: gen.label, status: "written" })
          continue
        }
        p.log.warn(`${pc.dim(gen.label)} already exists (use --force to overwrite)`)
        results.push({ label: gen.label, status: "skipped" })
        continue
      }

      if (dir && !existsSync(dir)) {
        mkdirSync(dir, { recursive: true })
      }

      let content: string
      if (fileExists && gen.merge) {
        const existing = readFileSync(path, "utf-8")
        content = gen.merge(existing, gen.generate(ir))
      } else if (gen.merge) {
        content = gen.merge("", gen.generate(ir))
      } else {
        content = gen.generate(ir)
      }

      writeFileSync(path, content, "utf-8")
      results.push({ label: gen.label, status: "written" })
    }

    const written = results.filter((r) => r.status === "written").length
    const skipped = results.filter((r) => r.status === "skipped").length

    s.stop(`Generated ${written} file(s)` + (skipped > 0 ? ` (${skipped} skipped)` : ""))

    console.log(`\n${pc.bold("Results:")}`)
    for (const r of results) {
      const icon = r.status === "written" ? pc.green("✓") : r.status === "skipped" ? pc.dim("—") : pc.dim("~")
      console.log(`  ${icon} ${r.label}`)
    }

    p.outro(pc.green("✔") + " AI sync complete")
  })
